import React from 'react';
import { AbsoluteFill, Audio, Sequence, staticFile, useCurrentFrame, spring } from 'remotion';
import TIMING from './metastatic-cascade-bottleneck-timing.json';
import { ClaudeComposerAsk, claudeComposerAskSchema } from './scenes/ClaudeComposerAsk';
import { ClaudeCodeBeat, claudeCodeBeatSchema } from './scenes/ClaudeCodeBeat';
import { ClaudeWindow, claudeWindowSchema } from './scenes/ClaudeWindow';
import { ClaudeTitleOutro, claudeTitleOutroSchema } from './scenes/ClaudeTitleOutro';
import { CLAUDE, CLAUDE_FONT } from './tokens/claude';

const SERIF = CLAUDE_FONT.serif;
const SANS  = CLAUDE_FONT.ui;
const TOPIC = 'CANCER BIOLOGY';
const SEGMENT = 'Metastatic Cascade';
const FOLDER = '@NikBearBrown';

// ── Slate for DOCUMENT beats ──────────────────────────────────────────────────
const SlateBeat: React.FC<{
  beatId: string;
  narration: string;
  slotNote: string;
  sparkLine: string;
}> = ({ beatId, narration, slotNote, sparkLine }) => {
  const frame = useCurrentFrame();
  const fps = 30;
  const cardIn = spring({ frame, fps, config: { damping: 28, stiffness: 140, mass: 0.8 } });
  const sparkIn = spring({ frame: frame - 20, fps, config: { damping: 28, stiffness: 140, mass: 0.8 } });
  const clamp = (v: number, a: number, b: number) => Math.min(b, Math.max(a, v));

  return (
    <AbsoluteFill style={{
      background: '#2F2A26',
      alignItems: 'center',
      justifyContent: 'center',
      flexDirection: 'column',
      padding: '0 10%',
    }}>
      <div style={{
        fontFamily: SANS,
        fontSize: 14,
        fontWeight: 700,
        letterSpacing: 3,
        textTransform: 'uppercase' as const,
        color: CLAUDE.SPARK,
        opacity: clamp(cardIn, 0, 1),
        marginBottom: 24,
      }}>
        SLOT — {beatId} · production media pending
      </div>
      <div style={{
        fontFamily: SERIF,
        fontSize: 108,
        fontWeight: 700,
        color: '#F3EBDD',
        letterSpacing: '-0.03em',
        lineHeight: 1,
        opacity: clamp(cardIn, 0, 1),
        transform: `scale(${clamp(cardIn, 0, 1)})`,
      }}>
        {beatId}
      </div>
      <div style={{
        fontFamily: SERIF,
        fontSize: 22,
        color: '#F3EBDD',
        textAlign: 'center',
        lineHeight: 1.5,
        marginTop: 28,
        maxWidth: 780,
        opacity: clamp(cardIn * 0.9, 0, 1),
      }}>
        {narration}
      </div>
      <div style={{
        fontFamily: SANS,
        fontSize: 15,
        color: CLAUDE.SPARK,
        marginTop: 20,
        textAlign: 'center',
        maxWidth: 680,
        opacity: clamp(cardIn * 0.8, 0, 1),
      }}>
        PIPELINE → {slotNote}
      </div>
      <div style={{
        position: 'absolute',
        bottom: '6%',
        left: 0,
        right: 0,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        gap: 10,
        opacity: clamp(sparkIn, 0, 1),
      }}>
        <svg width={18} height={18} viewBox="0 0 24 24" style={{ flexShrink: 0 }}>
          {Array.from({ length: 8 }, (_, i) => (
            <line key={i} x1={12} y1={12}
              x2={12 + 10 * Math.cos((i * Math.PI) / 4 + 0.2)}
              y2={12 + 10 * Math.sin((i * Math.PI) / 4 + 0.2)}
              stroke={CLAUDE.SPARK} strokeWidth={3.2} strokeLinecap="round" />
          ))}
        </svg>
        <span style={{
          fontFamily: SERIF,
          fontSize: 22,
          fontStyle: 'italic',
          color: '#F3EBDD',
        }}>
          {sparkLine}
        </span>
      </div>
    </AbsoluteFill>
  );
};

// ── Timing ────────────────────────────────────────────────────────────────────
const TIMED = TIMING.map((t) => ({ ...t }));
export const TOTAL_FRAMES = TIMED.reduce((a, b) => a + b.frames, 0);

// ── Main composition ──────────────────────────────────────────────────────────
export const MetastaticCascadeBottleneck: React.FC = () => {
  let at = 0;

  const seqs = TIMED.map((t) => {
    const from = at;
    at += t.frames;
    let content: React.ReactNode = null;

    switch (t.id) {
      // ── B00 — cold open ───────────────────────────────────────────────────────
      case 'B00':
        content = (
          <ClaudeComposerAsk {...claudeComposerAskSchema.parse({
            greeting: `Annyeong, Liam`,
            topic: TOPIC,
            segment: SEGMENT,
            command: `The metastatic cascade — why 99.99 percent of cancer cells that escape never succeed.`,
            runningText: `reading the research…`,
            folderLabel: FOLDER,
          })} />
        );
        break;

      // ── B01 — THE-PROBLEM (SLOT) ─────────────────────────────────────────────
      case 'B01':
        content = (
          <SlateBeat
            beatId='B01'
            narration={`A primary tumor sheds a million cells into the bloodstream every day. Almost none of them form metastases. The cells that do succeed kill 90 percent of cancer patients. Metastasis is the most lethal step in cancer — and it fails almost every time it's attempted. The question is what makes the surviving one in a hundred thousand different.`}
            slotNote='fill media/B01.png'
            sparkLine={`A million shed. Almost none metastasize.`}
          />
        );
        break;

      // ── B02 — THE-ASK ────────────────────────────────────────────────────────
      case 'B02':
        content = (
          <ClaudeComposerAsk {...claudeComposerAskSchema.parse({
            greeting: 'The ask,',
            topic: TOPIC,
            segment: SEGMENT,
            command: `Research the metastatic cascade step by step: intravasation, survival in circulation, extravasation, micrometastasis formation, dormancy, and outgrowth. For each step, give the quantitative attrition (what fraction of cells survive to the next step), the key molecular bottleneck, and the strongest therapeutic strategy targeting that step.`,
            runningText: `researching metastasis...`,
            folderLabel: FOLDER,
          })} />
        );
        break;

      // ── B03 — THE-SCRIPT (ClaudeCodeBeat) ───────────────────────────────────
      case 'B03':
        content = (
          <ClaudeCodeBeat {...claudeCodeBeatSchema.parse({
            title: `cascade_funnel.py — the count, not the claim`,
            code: `import math
STEPS = [
    ("Shed from primary",      1_000_000, "Tumor vasculature remodeling"),
    ("Survive intravasation",      5_000, "Anoikis resistance"),
    ("Survive circulation",          500, "NK cell evasion, shear stress"),
    ("Extravasate",                   50, "CXCR4-CXCL12 homing"),
    ("Form micromet",                  5, "ECM attachment, dormancy exit"),
    ("Form macrometastasis",           1, "Angiogenic switch"),
]
for i, (step, n, bottleneck) in enumerate(STEPS):
    if i > 0:
        survival = n / STEPS[i-1][1] * 100
        print(f"  -> {survival:.3f}% survive")
    print(f"{step}: ~{n:,}  [{bottleneck}]")`,
            sparkLine: `The script does the counting.`,
          })} />
        );
        break;

      // ── B04 — THE-OUTPUT (SLOT) ──────────────────────────────────────────────
      case 'B04':
        content = (
          <SlateBeat
            beatId='B04'
            narration={`Funnel visualization — 10 to the 6 shed per day, 5000 survive intravasation, 500 survive circulation, 50 extravasate, 5 form micromet, 1 in 100000 forms macrometastasis.`}
            slotNote='fill media/B04.png'
            sparkLine={`One million to five — the funnel.`}
          />
        );
        break;

      // ── B05 — THE-REVISION-ASK ───────────────────────────────────────────────
      case 'B05':
        content = (
          <ClaudeComposerAsk {...claudeComposerAskSchema.parse({
            greeting: 'The ask,',
            topic: TOPIC,
            segment: SEGMENT,
            command: `For each bottleneck step, what is the most advanced clinical-stage drug or intervention targeting it, its phase, and the primary endpoint being measured?`,
            runningText: `finding intervention targets...`,
            folderLabel: FOLDER,
          })} />
        );
        break;

      // ── B06 — THE-REVISED-OUTPUT (SLOT) ─────────────────────────────────────
      case 'B06':
        content = (
          <SlateBeat
            beatId='B06'
            narration={`Same funnel with intervention callout boxes at each bottleneck step.`}
            slotNote='fill media/B06.png'
            sparkLine={`Every bottleneck, every intervention.`}
          />
        );
        break;

      // ── B07 — VERDICT (ClaudeWindow artifact) ────────────────────────────────
      case 'B07':
        content = (
          <ClaudeWindow {...claudeWindowSchema.parse({
            view: 'artifact',
            artifactTitle: `Metastatic cascade bottlenecks — the teardown, one page`,
            artifactHeading: `Where the math says the opportunity is`,
            artifactLines: [
              `Approved therapies target macrometastasis — the last step.`,
              `Earlier bottlenecks already kill most cells — the opportunity is there.`,
              `The math: 10⁶ shed per day, ≈5 establish — three steps before clinical detection.`,
              `Challenge: building a trial around a step that precedes measurable disease.`,
            ],
            sparkLine: `Approved drugs hit step ten. Step two is open.`,
          })} />
        );
        break;

      // ── B08 — HANDOFF (Your turn.) ───────────────────────────────────────────
      case 'B08':
        content = (
          <ClaudeComposerAsk {...claudeComposerAskSchema.parse({
            greeting: 'Your turn.',
            topic: TOPIC,
            segment: SEGMENT,
            command: `Read Chambers et al. 2002 in Nature Reviews Cancer — the original quantification of metastatic inefficiency. Then read Liu et al. 2019 in Nature Cell Biology on dormancy reactivation. Find the single molecular event that converts a dormant micromet to an active one — that event is a therapeutic target.`,
            runningText: `paste this into Claude…`,
            folderLabel: FOLDER,
          })} />
        );
        break;

      // ── B09 — OUTRO (ClaudeTitleOutro) ──────────────────────────────────────
      case 'B09':
        content = (
          <ClaudeTitleOutro {...claudeTitleOutroSchema.parse({
            title: `Metastatic Cascade.`,
            handle: `@NikBearBrown`,
            subline: `Liam, in for Bear · build it, then take it apart`,
          })} />
        );
        break;

      default:
        content = <AbsoluteFill style={{ background: CLAUDE.PAGE }} />;
    }

    return (
      <Sequence key={t.id} from={from} durationInFrames={t.frames}>
        {content}
        <Audio src={staticFile(t.audio)} />
      </Sequence>
    );
  });

  return (
    <AbsoluteFill style={{ background: CLAUDE.PAGE }}>
      {seqs}
    </AbsoluteFill>
  );
};
