DEFAULT_LOG = BOOKS_DIR / "CLI-EXPLAINERS-OVERNIGHT-LOG.md"

GREETINGS = [
    "Hey", "Hola", "Ciao", "Salut", "Yo", "Oi", "Merhaba",
    "Szia", "Ahoj", "Hei", "Hej", "Olá", "Namaste", "Yalla", "Annyeong",
    "Aloha", "Shalom", "Ciao", "Bonjour", "G'day",
]


def greeting_for(slug: str) -> str:
    return GREETINGS[abs(hash(slug)) % len(GREETINGS)]


def make_title(slug: str, note: str) -> str:
    concept = note.split(";")[0].strip()
    concept = concept[:1].upper() + concept[1:]
    return f"{concept} — with Claude"


def extract_code(html_path: Path, max_lines: int = 20, max_width: int = 78) -> str:
    """Pull the ACTUAL code out of the sim's single-file HTML for the CODE beat.

    THE ACTUAL-CODE LAW (terminal-screencast skill): the CODE beat shows the
    real source that ran — the sim's own inline JS, trimmed to what teaches —
    never pseudocode. Heuristic: take the longest inline <script> block, skip
    the d3 CDN import lines, and keep the first `max_lines` meaningful lines.
    """
    try:
        html = html_path.read_text(errors="replace")
    except OSError:
        return "// source unavailable"

    import re
    blocks = re.findall(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>",
                        html, re.DOTALL | re.IGNORECASE)
    if not blocks:
        return "// no inline script found"
    js = max(blocks, key=len)

    lines, blank_run = [], 0
    for raw in js.splitlines():
        line = raw.rstrip()
        if not line.strip():
            blank_run += 1
            if blank_run > 1 or not lines:
                continue
        else:
            blank_run = 0
        if len(line) > max_width:
            line = line[: max_width - 1] + "…"
        lines.append(line)
        if len(lines) >= max_lines:
            break

    code = "\n".join(lines).strip()
    return (f"// {html_path.name} — generated by Claude Code (trimmed)\n"
            f"{code}\n// … trimmed — full source: {html_path.name}")


def remotion_shot(pattern: str, props: dict, beat_id: str) -> dict:
    """Canonical Remotion shot — the format remotion_scenes.py + compile.py read."""
    return {
        "type": "GRAPHIC",
        "source": "remotion",
        "motion": "fade",
        "remotion": {
            "pattern": pattern,
            "provenance": f"proven-core/{pattern}",
            "version": "1",
            "props": props,
            "rendered": {"out": f"media/{beat_id}.mp4", "at": ""},
        },
    }


def make_beat_sheet(sim: dict, reel_slug: str, code: str) -> dict:
    slug   = sim["slug"]
