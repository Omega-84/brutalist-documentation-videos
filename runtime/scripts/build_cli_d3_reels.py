def run(cmd, timeout=600, env=None):
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout,
                       env=env or os.environ.copy())
    out = (r.stdout + "\n" + r.stderr).strip()
    return r.returncode, out


def append_log(log_file: Path, slug, book, lane, status, mp4, note):
    line = f"| {slug} | {book} | {lane} | {status} | {mp4} | {note} |\n"
    with open(log_file, "a") as f:
        f.write(line)


def build_one(sim: dict, log_file: Path) -> str:
    slug      = sim["slug"]
    book      = sim["book"]
    html_path = Path(sim["html"])
    reel_slug = f"claude-liam-cli-{slug}"
    reel_dir  = BOOKS_DIR / book / "youtube" / reel_slug

    review_mp4 = reel_dir / f"{reel_slug}-slate.mp4"
    if review_mp4.exists() and review_mp4.stat().st_size > 50_000:
        note = f"already built ({review_mp4.stat().st_size // 1024}KB)"
        print(f"[build] SKIP {reel_slug}  ({note})", flush=True)
        append_log(log_file, slug, book, "D3", "SKIP", str(review_mp4), note)
        return "SKIP"

    print(f"\n{'='*60}", flush=True)
    print(f"[build] START  {reel_slug}", flush=True)

    env = os.environ.copy()
    env["ART_HOME"] = str(ART_HOME)

    try:
        if not html_path.exists():
            raise RuntimeError(f"HTML not found: {html_path}")

        reel_dir.mkdir(parents=True, exist_ok=True)
        (reel_dir / "media").mkdir(exist_ok=True)
        (reel_dir / "mp3").mkdir(exist_ok=True)

        code = extract_code(html_path)
        bs = make_beat_sheet(sim, reel_slug, code)
        (reel_dir / "beat_sheet.json").write_text(json.dumps(bs, indent=2))
        print(f"[build] beat_sheet.json written (Claude skin, actual code)", flush=True)

        print(f"[build] capturing {slug}...", flush=True)
        rc, out = run(
            ["python3", str(SCRIPTS / "capture_sim.py"), str(html_path), str(reel_dir)],
            timeout=240, env=env,
        )
        if rc != 0:
            raise RuntimeError(f"capture_sim: {out[-400:]}")
        out_mp4  = reel_dir / "media" / "output.mp4"
        chg_mp4  = reel_dir / "media" / "change.mp4"
        if not (out_mp4.exists() and chg_mp4.exists()):
            raise RuntimeError("capture_sim produced no output mp4")
        print(f"[build] captured output={out_mp4.stat().st_size//1024}KB "
              f"change={chg_mp4.stat().st_size//1024}KB", flush=True)

        shutil.copy(out_mp4,  reel_dir / "media" / "B04.mp4")
        shutil.copy(chg_mp4,  reel_dir / "media" / "B06.mp4")

        print(f"[build] generating audio...", flush=True)
        rc, out = run(
            ["python3", str(SCRIPTS / "generate_audio_kokoro.py"),
             str(reel_dir), "--no-gate"],
            timeout=600, env=env,
        )
        if rc != 0:
            raise RuntimeError(f"audio: {out[-400:]}")
        print(f"[build] audio done", flush=True)

        # Render the Claude-skin Remotion beats (B00/B02/B03/B08/B09) to
        # media/<BID>.mp4. Soft-fail: compile.py falls back to slates for
        # any beat that didn't render.
        print(f"[build] rendering Claude Remotion beats...", flush=True)
        rc, out = run(
            ["python3", str(SCRIPTS / "remotion_scenes.py"), str(reel_dir)],
            timeout=900, env=env,
        )
        if rc != 0:
            print(f"[build] WARN remotion_scenes failed — Claude beats stay "
                  f"slates: {out[-300:]}", flush=True, file=sys.stderr)

        print(f"[build] compiling review cut...", flush=True)
        rc, out = run(
            ["python3", str(SCRIPTS / "compile.py"), str(reel_dir), "--review"],
            timeout=600, env=env,
        )

        # final cut too — clean master when no slates remain (soft-fail otherwise)
        run(["python3", str(SCRIPTS / "compile.py"), str(reel_dir)],
            timeout=600, env=env)
        if rc != 0:
            raise RuntimeError(f"compile: {out[-400:]}")

        if not review_mp4.exists():
            raise RuntimeError(f"review mp4 not found at {review_mp4}")
        size = review_mp4.stat().st_size
        if size < 50_000:
            raise RuntimeError(f"review mp4 suspiciously small: {size} bytes")

        note = f"{size // 1024}KB"
        print(f"[build] DONE  {reel_slug}  ({note})", flush=True)
        append_log(log_file, slug, book, "D3", "BUILT", str(review_mp4), note)
        return "BUILT"

    except Exception as e:
        note = str(e)[:250].replace("|", "/").replace("\n", " ")
        print(f"[build] FAIL  {reel_slug}: {note}", flush=True, file=sys.stderr)
        append_log(log_file, slug, book, "D3", "FAILED", "-", note)
        return f"FAILED: {note}"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("config", help="JSON config with sim list")
    ap.add_argument("--log", default=str(DEFAULT_LOG))
    a = ap.parse_args()

    cfg = json.loads(Path(a.config).read_text())
    sims = cfg["sims"]
    log  = Path(a.log)

    print(f"[build_cli_d3_reels] {len(sims)} sims  log={log}", flush=True)

    counts = {}
    for i, sim in enumerate(sims):
        print(f"\n[build_cli_d3_reels] [{i+1}/{len(sims)}] {sim['slug']}", flush=True)
        result = build_one(sim, log)
        key = result.split(":")[0]
        counts[key] = counts.get(key, 0) + 1

    print(f"\n[build_cli_d3_reels] FINISHED: {counts}", flush=True)


if __name__ == "__main__":
    main()
